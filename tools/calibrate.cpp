// Generates src/engine/CalibrationTables.hpp: the pitch at which each model
// family actually sounds, relative to its nominal delay-line pitch, at the
// voiced operating point. The engine uses it to tune every pipe exactly while
// keeping the physical pitch drift when pressure changes during play.
#include "../src/engine/PipeModels.hpp"
#include <cstdio>
#include <vector>
#include <memory>
#include <cmath>
using namespace pipe;

static const double fs = 48000.0;
static const double kLfMin = -11.5, kLfStep = 0.25; static const int kLfN = 37;      // log2(f/fs)
static const double kJrMin = 0.30, kJrStep = 0.02; static const int kJrN = 18;       // jet ratio

static double acorr(const std::vector<float>& x, int start, double L) {
    int Li = (int)L; double fr = L - Li; double acc = 0, e1 = 0, e2 = 0;
    int n = (int)x.size();
    for (int i = start; i + Li + 1 < n; ++i) {
        double y = x[i + Li] * (1 - fr) + x[i + Li + 1] * fr;
        acc += x[i] * y; e1 += x[i] * x[i]; e2 += y * y;
    }
    return acc / std::sqrt(e1 * e2 + 1e-30);
}
// returns cents of sounding pitch vs f, or NAN if not speaking the fundamental
static double measure(const std::vector<float>& x, double f) {
    int n = (int)x.size(), start = n / 2;
    double rms = 0; for (int i = start; i < n; ++i) rms += x[i] * x[i];
    rms = std::sqrt(rms / (n - start));
    if (rms < 0.05) return NAN;
    double T = fs / f;
    int lo = (int)(T * 0.75), hi = (int)(T * 1.33) + 1;
    double best = -2; int bl = lo;
    std::vector<double> r(hi + 2);
    for (int L = lo - 1; L <= hi + 1; ++L) r[L] = acorr(x, start, L);
    for (int L = lo; L <= hi; ++L) if (r[L] > best) { best = r[L]; bl = L; }
    if (best < 0.9) return NAN;
    double a = r[bl - 1], b = r[bl], c = r[bl + 1];
    double p = 0.5 * (a - c) / (a - 2 * b + c);
    double Lp = bl + p;
    // reject overblown octave / twelfth: period would repeat at L/2 or L/3
    if (acorr(x, start, Lp / 2) > 0.85 || acorr(x, start, Lp / 3) > 0.85) return NAN;
    return 1200.0 * std::log2((fs / Lp) / f);
}
static std::vector<float> runFlue(int fam, double f, double jr) {
    static auto c = std::make_unique<FlueCore>();
    c->reset(); c->noise.seed(11);
    const auto& k = kFlueFamily[fam];
    double T = fs / f;
    c->sign = fam == kFamilyStopped ? -1.f : 1.f;
    c->boreDelay = (float)(fam == kFamilyStopped ? T / 2 : T);
    c->jetDelay = (float)(jr * T);
    c->aBore = onePoleCoef(k.boreFc * (float)f, (float)fs);
    c->aJet = onePoleCoef(k.jetFc * (float)f, (float)fs);
    c->aDc = onePoleCoef(kDcFc * (float)f, (float)fs);
    c->loopGain = k.loopGain;
    int N = (int)(fs * std::max(0.35, 50.0 / f));
    std::vector<float> x(N);
    for (int i = 0; i < N; ++i) { c->breath = kFlueVoicedBreath * (float)std::min(1.0, i / (0.01 * fs)); x[i] = c->tick(); }
    return x;
}
static std::vector<float> runReed(int fam, double f) {
    static auto c = std::make_unique<ReedCore>();
    c->reset(); c->noise.seed(11);
    const auto& k = kReedFamily[fam];
    double D = fs / f;
    c->delayA = (float)((1 - k.position) * D); c->delayB = (float)(k.position * D);
    c->reedSlope = k.slope; c->reedOffset = 0.7f;
    c->aBore = onePoleCoef(k.boreFc * (float)f, (float)fs);
    c->aDc = onePoleCoef(kDcFc * (float)f, (float)fs);
    int N = (int)(fs * std::max(0.35, 50.0 / f));
    std::vector<float> x(N);
    for (int i = 0; i < N; ++i) { c->breath = kReedVoicedBreath * (float)std::min(1.0, i / (0.01 * fs)); x[i] = c->tick(); }
    return x;
}
static void fillGaps(std::vector<double>& row) {
    // nearest valid neighbour fill along the row, then flat extrapolation
    int n = (int)row.size();
    for (int i = 0; i < n; ++i) if (std::isnan(row[i])) {
        int l = i - 1; while (l >= 0 && std::isnan(row[l])) --l;
        int r = i + 1; while (r < n && std::isnan(row[r])) ++r;
        if (l >= 0 && r < n) row[i] = row[l] + (row[r] - row[l]) * double(i - l) / double(r - l);
        else if (l >= 0) row[i] = row[l];
        else if (r < n) row[i] = row[r];
        else row[i] = 0;
    }
}
int main() {
    FILE* o = fopen("src/engine/CalibrationTables.hpp", "w");
    fprintf(o, "// Generated by tools/calibrate.cpp - do not edit.\n// Sounding pitch (cents) relative to the nominal delay-line pitch at the voiced point.\n#pragma once\nnamespace pipe { namespace calib {\n");
    fprintf(o, "constexpr float kLfMin = %.4ff, kLfStep = %.4ff; constexpr int kLfN = %d;\n", kLfMin, kLfStep, kLfN);
    fprintf(o, "constexpr float kJrMin = %.4ff, kJrStep = %.4ff; constexpr int kJrN = %d;\n", kJrMin, kJrStep, kJrN);
    fprintf(o, "// [family][jetRatio][log2(f/fs)]\nconstexpr float kFlue[%d][%d][%d] = {\n", kNumFlueFamilies, kJrN, kLfN);
    int invalid = 0, total = 0;
    for (int fam = 0; fam < kNumFlueFamilies; ++fam) {
        std::vector<std::vector<double>> grid(kJrN, std::vector<double>(kLfN));
        for (int j = 0; j < kJrN; ++j) for (int l = 0; l < kLfN; ++l) {
            double f = fs * std::pow(2.0, kLfMin + l * kLfStep);
            double c = measure(runFlue(fam, f, kJrMin + j * kJrStep), f);
            grid[j][l] = c; ++total; if (std::isnan(c)) ++invalid;
        }
        // fill along frequency, then along jet ratio
        for (auto& row : grid) fillGaps(row);
        for (int l = 0; l < kLfN; ++l) { std::vector<double> col(kJrN); for (int j = 0; j < kJrN; ++j) col[j] = grid[j][l]; fillGaps(col); for (int j = 0; j < kJrN; ++j) grid[j][l] = col[j]; }
        fprintf(o, " {\n");
        for (int j = 0; j < kJrN; ++j) { fprintf(o, "  {"); for (int l = 0; l < kLfN; ++l) fprintf(o, "%.1ff%s", grid[j][l], l + 1 < kLfN ? "," : ""); fprintf(o, "},\n"); }
        fprintf(o, " },\n");
        fprintf(stderr, "flue family %d done\n", fam);
    }
    fprintf(o, "};\n// [family][log2(f/fs)]\nconstexpr float kReed[%d][%d] = {\n", kNumReedFamilies, kLfN);
    for (int fam = 0; fam < kNumReedFamilies; ++fam) {
        std::vector<double> row(kLfN);
        for (int l = 0; l < kLfN; ++l) { double f = fs * std::pow(2.0, kLfMin + l * kLfStep); row[l] = measure(runReed(fam, f), f); ++total; if (std::isnan(row[l])) ++invalid; }
        fillGaps(row);
        fprintf(o, " {"); for (int l = 0; l < kLfN; ++l) fprintf(o, "%.1ff%s", row[l], l + 1 < kLfN ? "," : ""); fprintf(o, "},\n");
    }
    fprintf(o, "};\n}} // namespace pipe::calib\n");
    fclose(o);
    fprintf(stderr, "cells: %d, not speaking fundamental: %d\n", total, invalid);
}
