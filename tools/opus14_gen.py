#!/usr/bin/env python3
"""Generate src/engine/Opus14Data.hpp from the hand transcriptions in data/opus14/.

Nothing is computed here: every number in the header is a number printed on the Pasi sheets.
Conversions only: "1/4" -> 0.25, "145x175" -> (145, 175), "600/1170" -> (600, 1170), "-" -> NaN.
Note names: C = MIDI 36 (low C of the 8' octave), c0 = 48, c1 = 60, e1 = 64, c2 = 72, c3 = 84, c4 = 96.
"""
import re, sys, pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
DATA = ROOT / "data" / "opus14"
NOTE = {"C": 36, "c0": 48, "c1": 60, "e1": 64, "c2": 72, "c3": 84, "c4": 96}
DIVS = {"HAUPTWERK": "kHW", "OBERWERK": "kOW", "UNTERWERK": "kUW", "PEDAL": "kPed"}
TEXT_ROWS = {"Material", "Shallots"}

def is_fraction(tok):
    # "1/4", "2/7": a printed fraction of a millimetre (or of the circumference for mouth widths).
    # Pairs such as "1110/2250", "9/9", "44/25.5" are two values.
    m = re.fullmatch(r"(\d)/(\d)", tok)
    return bool(m) and int(m.group(1)) < int(m.group(2))

def num(tok):
    if tok == "-": return ("kNaN", "kNaN")
    if is_fraction(tok):
        a, b = tok.split("/"); return (fmt(float(a) / float(b)), "kNaN")
    for sep in ("x", "/"):
        if sep in tok:
            a, b = tok.split(sep)
            return (fmt(float(a)), fmt(float(b)))
    return (fmt(float(tok)), "kNaN")

def fmt(x): return repr(float(x)) + "f"

def feet(name):
    m = re.search(r"(\d+)(?: (\d)/(\d))?'", name)
    if not m:
        m2 = re.search(r"(\d)/(\d)'", name)
        return float(m2.group(1)) / float(m2.group(2))
    f = float(m.group(1))
    if m.group(2): f += float(m.group(2)) / float(m.group(3))
    return f

def cident(s): return re.sub(r"[^A-Za-z0-9]+", "_", s).strip("_")

def parse_scales(path, kind):
    stops, div = [], None
    for raw in open(path, encoding="utf-8"):
        line = raw.rstrip("\n")
        if not line.strip() or line.lstrip().startswith("#"): continue
        if line.startswith("["):
            div = DIVS[line.strip("[]")]; continue
        if line.startswith("stop:"):
            parts = [p.strip() for p in line[5:].split("|")]
            st = {"div": div, "name": parts[0], "cols": parts[1].split(), "rows": [], "text": {}, "note": "", "kind": kind}
            for p in parts[2:]:
                if p.startswith("note:"): st["note"] = p[5:].strip()
            stops.append(st); continue
        label, vals = [p.strip() for p in line.split("|", 1)]
        st = stops[-1]
        if label in TEXT_ROWS:
            st["text"][label] = vals; continue
        toks = vals.split()
        # "a / b" written with spaces is not used; tokens are single values
        if len(toks) != len(st["cols"]):
            sys.exit(f"{path}: {st['name']} row {label}: {len(toks)} values for {len(st['cols'])} columns")
        st["rows"].append((label, [num(t) for t in toks]))
    return stops

def parse_mixtures(path):
    mixes, cur = [], None
    for raw in open(path, encoding="utf-8"):
        line = raw.strip()
        if not line or line.startswith("#"): continue
        if line.startswith("["):
            d, name = line[1:].split("]", 1)
            cur = {"div": DIVS[d], "name": name.strip(), "breaks": []}; mixes.append(cur); continue
        key, ranks = [p.strip() for p in line.split("|")]
        knote = {"C": 36, "c0": 48, "f#0": 54, "c1": 60, "c2": 72, "c3": 84}[key]
        fs = []
        for r in ranks.split(","):
            r = r.strip(); parts = r.split()
            f = 0.0
            for p in parts:
                if "/" in p: a, b = p.split("/"); f += float(a) / float(b)
                else: f += float(p)
            fs.append(f)
        cur["breaks"].append((knote, fs))
    return mixes

def emit(stops, mixes):
    o = []
    w = o.append
    w("// GENERATED by tools/opus14_gen.py from data/opus14/*.txt - do not edit by hand.")
    w("// Pasi Opus 14 pipe scales as printed by the builder (see data/opus14 for sources and GAPS.md).")
    w("// Millimetres. NaN = not given. Mouth Width values <= 1 are fractions of the circumference.")
    w("// Pairs: \"a x b\" (rectangular: width x depth) and \"a / b\" (two pipes or constructions at one note)")
    w("// are value + alt; alt is NaN otherwise.")
    w("#pragma once")
    w("#include <limits>")
    w("namespace pipe { namespace opus14 {")
    w("enum Division { kHW = 0, kOW, kUW, kPed, kNumDivs };")
    w("enum Kind { kFlue = 0, kReed };")
    w("constexpr float kNaN = std::numeric_limits<float>::quiet_NaN();")
    w("struct Row { const char* label; float v[7]; float alt[7]; };")
    w("struct Stop { Division div; Kind kind; const char* name; float feet; int nCols; int key[7];")
    w("              const Row* rows; int nRows; const char* material; const char* shallots; const char* note; };")
    for i, st in enumerate(stops):
        rows = []
        for label, vals in st["rows"]:
            v = [a for a, b in vals] + ["kNaN"] * (7 - len(vals))
            alt = [b for a, b in vals] + ["kNaN"] * (7 - len(vals))
            rows.append(f'    {{ "{label}", {{ {", ".join(v)} }}, {{ {", ".join(alt)} }} }},')
        w(f"static const Row kRows{i}[] = {{  // {st['name']}")
        o.extend(rows)
        w("};")
    w("static const Stop kStops[] = {")
    for i, st in enumerate(stops):
        keys = [str(NOTE[c]) for c in st["cols"]] + ["0"] * (7 - len(st["cols"]))
        mat = st["text"].get("Material", "").replace('"', '\\"')
        sh = st["text"].get("Shallots", "").replace('"', '\\"')
        nt = st["note"].replace('"', '\\"')
        w(f'    {{ {st["div"]}, {"kReed" if st["kind"] == "reed" else "kFlue"}, "{st["name"]}", {fmt(feet(st["name"]))}, '
          f'{len(st["cols"])}, {{ {", ".join(keys)} }}, kRows{i}, {len(st["rows"])}, "{mat}", "{sh}", "{nt}" }},')
    w("};")
    w(f"constexpr int kNumStops = {len(stops)};")
    w("struct MixBreak { int key; int nRanks; float feet[5]; };")
    w("struct Mixture { Division div; const char* name; int nBreaks; MixBreak breaks[6]; };")
    w("static const Mixture kMixtures[] = {")
    for m in mixes:
        bs = []
        for k, fs in m["breaks"]:
            ff = [fmt(f) for f in fs] + ["0.f"] * (5 - len(fs))
            bs.append(f'{{ {k}, {len(fs)}, {{ {", ".join(ff)} }} }}')
        w(f'    {{ {m["div"]}, "{m["name"]}", {len(m["breaks"])}, {{ {", ".join(bs)} }} }},')
    w("};")
    w(f"constexpr int kNumMixtures = {len(mixes)};")
    w("}} // namespace pipe::opus14")
    return "\n".join(o) + "\n"

stops = parse_scales(DATA / "flue.txt", "flue") + parse_scales(DATA / "reeds.txt", "reed")
mixes = parse_mixtures(DATA / "mixtures.txt")
out = ROOT / "src" / "engine" / "Opus14Data.hpp"
out.write_text(emit(stops, mixes), encoding="utf-8")
print(f"{len(stops)} stops/ranks, {len(mixes)} mixtures -> {out}")
